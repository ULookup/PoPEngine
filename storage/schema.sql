-- 为阶段三隔离样例创建计数、操作结果、事件认领及消费去重表。

CREATE TABLE IF NOT EXISTS sample_counter (
  aggregate_id BIGINT UNSIGNED PRIMARY KEY,
  value BIGINT UNSIGNED NOT NULL DEFAULT 0,
  version BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sample_operation (
  operation_id BIGINT UNSIGNED PRIMARY KEY,
  aggregate_id BIGINT UNSIGNED NOT NULL,
  delta BIGINT UNSIGNED NOT NULL,
  version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  value BIGINT UNSIGNED NOT NULL DEFAULT 0,
  committed_at_ms BIGINT UNSIGNED NOT NULL DEFAULT 0,
  INDEX sample_history (aggregate_id, version)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sample_outbox (
  event_id BIGINT UNSIGNED PRIMARY KEY,
  state TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0 开放，1 已发布，2 隔离',
  available_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  generation BIGINT UNSIGNED NOT NULL DEFAULT 0,
  attempt BIGINT UNSIGNED NOT NULL DEFAULT 0,
  INDEX sample_due (state, available_at, event_id),
  FOREIGN KEY (event_id) REFERENCES sample_operation(operation_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sample_inbox (
  event_id BIGINT UNSIGNED PRIMARY KEY,
  aggregate_id BIGINT UNSIGNED NOT NULL,
  version BIGINT UNSIGNED NOT NULL,
  value BIGINT UNSIGNED NOT NULL,
  committed_at_ms BIGINT UNSIGNED NOT NULL,
  applied TINYINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sample_projection (
  aggregate_id BIGINT UNSIGNED PRIMARY KEY,
  value BIGINT UNSIGNED NOT NULL DEFAULT 0,
  version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  applications BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
